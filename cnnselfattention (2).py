"""## Grad-CAM (Gradient-weighted Class Activation Mapping)

Grad-CAM helps visualize the regions in the input that are most important for the model's classification decision. It does this by using the gradients of the target concept (e.g., the predicted class score) flowing into the final convolutional layer. The heatmaps generated by Grad-CAM highlight discriminative regions in the input that contribute to the model's prediction.

### Visualizing Attention Map and Grad-CAM for all Classes

To ensure we examine how the model attends to and highlights features for each distinct sound category, we will now generate Attention Map and Grad-CAM visualizations for a sample from each class. We will iterate through all unique class IDs, find the first available sample in `y_test` for that class, and then plot the visualizations.

### Attention Consistency Test

To evaluate the robustness of our attention mechanism, we will perform an **Attention Consistency Test**. This involves:

1.  Selecting a sample from each class.
2.  Generating its original attention map.
3.  Creating slightly shifted versions of the input spectrogram (e.g., shifting by a few pixels horizontally and vertically).
4.  Generating attention maps for these shifted input spectrograms.
5.  Visually comparing the original and shifted attention maps to see if the model's focus remains consistent despite minor input perturbations. Ideally, the attention should still highlight the same critical regions.
"""

from scipy.ndimage import shift as ndimage_shift

def shift_spectrogram(spectrogram_2d, shift_pixels=(0, 0)):
    """
    Shifts a 2D spectrogram.

    Args:
        spectrogram_2d (np.ndarray): The 2D spectrogram (e.g., original_spectrogram[0, :, :, 0]).
        shift_pixels (tuple): (shift_y, shift_x) in pixels.

    Returns:
        np.ndarray: The shifted 2D spectrogram.
    """
    # Note: ndimage_shift expects (height_shift, width_shift)
    # We use mode='constant' and cval=spectrogram_2d.min() to fill new areas with the minimum spectrogram value
    return ndimage_shift(spectrogram_2d, shift_pixels, mode='constant', cval=spectrogram_2d.min())

