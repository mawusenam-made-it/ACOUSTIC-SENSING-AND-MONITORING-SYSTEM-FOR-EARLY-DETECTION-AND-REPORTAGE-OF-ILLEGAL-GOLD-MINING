class SelfAttention(layers.Layer):
    def __init__(self, channels):
        super(SelfAttention, self).__init__()
        self.channels = channels
        self.query_conv = layers.Conv2D(channels // 8, kernel_size=1, padding='same')
        self.key_conv = layers.Conv2D(channels // 8, kernel_size=1, padding='same')
        self.value_conv = layers.Conv2D(channels, kernel_size=1, padding='same')
        self.gamma = self.add_weight(name='gamma', shape=[1], initializer='zeros', trainable=True)

    def call(self, x):
        batch_size, height, width, C = x.get_shape().as_list()

        proj_query = self.query_conv(x)
        proj_query = K.reshape(proj_query, (-1, height * width, C // 8))
        proj_key = self.key_conv(x)
        proj_key = K.reshape(proj_key, (-1, height * width, C // 8))

        energy = K.batch_dot(proj_query, proj_key, axes=(2, 2))  # (B, N, N)
        attention = K.softmax(energy)

        proj_value = self.value_conv(x)
        proj_value = K.reshape(proj_value, (-1, height * width, self.channels))

        out = K.batch_dot(attention, proj_value)
        out = K.reshape(out, (-1, height, width, self.channels))

        out = self.gamma * out + x
        return out

def build_cnn_attention_model(input_shape, num_classes):
    model_input = layers.Input(shape=input_shape)

    x = model_input

    # First Convolutional Block
    x = layers.Conv2D(32, kernel_size=(3, 3), activation='relu', padding='same')(x)
    x = layers.BatchNormalization()(x)
    x = layers.MaxPooling2D(pool_size=(2, 2))(x)

    # Second Convolutional Block
    x = layers.Conv2D(64, kernel_size=(3, 3), activation='relu', padding='same')(x)
    x = layers.BatchNormalization()(x)
    x = layers.MaxPooling2D(pool_size=(2, 2))(x)

    # Third Convolutional Block
    x = layers.Conv2D(128, kernel_size=(3, 3), activation='relu', padding='same')(x)
    x = layers.BatchNormalization()(x)
    x = layers.MaxPooling2D(pool_size=(2, 2))(x)

    # Self-Attention Layer
    # We need to ensure the channel dimension is explicit for the attention layer
    attention_channels = x.shape[-1]
    x = SelfAttention(attention_channels)(x)

    # Global Average Pooling
    x = layers.GlobalAveragePooling2D()(x)

    # Dense Layers
    x = layers.Dense(256, activation='relu')(x)
    x = layers.Dropout(0.5)(x)

    # Output Layer
    model_output = layers.Dense(num_classes, activation='softmax')(x)

    model = models.Model(inputs=model_input, outputs=model_output)
    return model

