"""## Build the CNN + Self-Attention Model

We will now define the architecture for our Convolutional Neural Network (CNN) combined with a Self-Attention mechanism. The model will consist of:

1.  **Input Layer**: Takes the log-mel spectrograms as input.
2.  **Convolutional Blocks**: Multiple `Conv2D` layers followed by `BatchNormalization` and `ReLU` activation for feature extraction. `MaxPooling2D` layers will be used for downsampling.
3.  **Self-Attention Mechanism**: A custom or standard attention layer to focus on the most relevant features across the feature maps.
4.  **Global Average Pooling**: Reduces the spatial dimensions of the feature maps.
5.  **Dense Layers**: Fully connected layers for classification.
6.  **Output Layer**: A `Dense` layer with `softmax` activation for multi-class classification.
"""

import tensorflow as tf
from tensorflow.keras import layers, models, backend as K

# Define the input shape based on X_train
# X_train shape is (num_samples, num_mel_bins, num_time_steps)
# For Conv2D, we usually need (height, width, channels). Here, channels=1.
