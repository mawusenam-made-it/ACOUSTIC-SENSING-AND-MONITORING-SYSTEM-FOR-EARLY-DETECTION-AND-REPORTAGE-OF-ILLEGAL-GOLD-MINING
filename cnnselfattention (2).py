FMAX = 8000 # Maximum frequency
TARGET_TIME_STEPS = 216 # Expected number of time steps for the spectrogram

def preprocess_audio_for_inference(audio_path, sr=SR, n_mels=N_MELS, fmax=FMAX, target_time_steps=TARGET_TIME_STEPS):
    """Loads an audio file, extracts its log-mel spectrogram, and reshapes it for model inference."""
    try:
        audio, _ = librosa.load(audio_path, sr=sr)
        mel_spectrogram = librosa.feature.melspectrogram(y=audio, sr=sr, n_mels=n_mels, fmax=fmax)
        log_mel_spectrogram = librosa.power_to_db(mel_spectrogram, ref=np.max)

        # Handle time steps: pad or crop to match TARGET_TIME_STEPS
        current_time_steps = log_mel_spectrogram.shape[1]
        if current_time_steps < target_time_steps:
            # Pad with zeros
            padding = np.zeros((n_mels, target_time_steps - current_time_steps))
            log_mel_spectrogram = np.concatenate((log_mel_spectrogram, padding), axis=1)
        elif current_time_steps > target_time_steps:
            # Crop
            log_mel_spectrogram = log_mel_spectrogram[:, :target_time_steps]

        # Reshape for model input: (1, N_MELS, TARGET_TIME_STEPS, 1)
        # Add batch dimension and channel dimension
        model_input = log_mel_spectrogram[np.newaxis, ..., np.newaxis]
        return model_input
    except Exception as e:
        print(f"Error processing {audio_path}: {e}")
        return None

